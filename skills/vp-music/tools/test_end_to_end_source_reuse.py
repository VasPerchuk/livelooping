"""True end-to-end source-reuse integration fixture (requirement 4).

This is the one test module that exercises the *entire* pipeline for real,
with nothing hand-derived or mocked in between:

  1. a hermetic modern-GP source asset is generated by `make_source_fixture.mjs`
     (no commercial song asset is read, copied, or persisted);
  2. a hand-authored v2 analysis manifest (`arrangement.json` shape) describing
     that asset is compiled by the real `compile_performance.py` CLI (not the
     pure Python function directly, and not a hand-rolled plan) into a real
     `performance-arrangement.json`;
  3. that compiled plan is built by the real `write_arrangement.mjs` writer
     (also exercising its `--analysis`/`--resolutions` freshness preflight) into
     a real `.gp` file;
  4. the resulting `.gp` is inspected bar-by-bar and track-by-track.

The manifest covers multiple sections, one instrument with two distinct LOOP
pattern output tracks (one of them reused — i.e. placed — across two separate,
non-adjacent sections) plus a LIVE track and a deferred UNRESOLVED track, all
on the same analysis track/instrument, matching requirement 4's scenario.
"""
import json
import hashlib
import subprocess
import tempfile
import unittest
from pathlib import Path

from compile_performance import main as compile_main
from music_assets import inspect
from v2_schema import canonical_sha256

HERE = Path(__file__).resolve().parent
WRITER = HERE / "write_arrangement.mjs"
FIXTURE_GEN = HERE / "make_source_fixture.mjs"


def make_fixture_bytes(**opts):
    result = subprocess.run(
        ["node", str(FIXTURE_GEN)],
        input=json.dumps(opts).encode("utf-8"),
        capture_output=True, timeout=60, check=False,
    )
    if result.returncode != 0:
        raise RuntimeError(result.stderr.decode("utf-8", "replace"))
    return result.stdout


def _ref(digest, rel_path, bars):
    return {"asset_sha256": digest, "asset_relative_path": rel_path, "track_index": 0,
            "track_name": "Fixture Guitar", "staff_index": 0,
            "written_master_bars": bars, "voice_indices": [0]}


class EndToEndSourceReuseTests(unittest.TestCase):
    def setUp(self):
        temp = tempfile.TemporaryDirectory(prefix="vp-e2e-")
        self.addCleanup(temp.cleanup)
        self.song_dir = Path(temp.name)
        self.source_dir = self.song_dir / "source"
        self.source_dir.mkdir(parents=True)
        self.tracking_dir = self.song_dir / ".vp-music-tracking" / "arrangement"
        self.tracking_dir.mkdir(parents=True)
        self.manifest_path = self.tracking_dir / "arrangement.json"
        self.resolutions_path = self.tracking_dir / "resolutions.json"
        self.performance_path = self.tracking_dir / "performance.json"
        self.output_path = self.tracking_dir / "performance-arrangement.json"
        self.gp_output = self.song_dir / "arrangement.gp"

    def _write_fixture(self, bars=4):
        data = make_fixture_bytes(bars=bars)
        path = self.source_dir / "fixture.gp"
        path.write_bytes(data)
        digest = hashlib.sha256(data).hexdigest()
        return "source/fixture.gp", digest

    def _manifest(self, rel_path, digest):
        ref_a = _ref(digest, rel_path, [1, 2])
        ref_b = _ref(digest, rel_path, [3, 4])
        return {
            "version": 2,
            "tempo_bpm": 120,
            "meter": "4/4",
            "source": {"asset_relative_path": rel_path, "asset_sha256": digest,
                      "format": "gpif", "capabilities": ["source_bar_reuse"]},
            "tracks": [{
                "id": "track-guitar", "name": "Guitar",
                "spans": [
                    {"id": "gtr-a", "disposition": "LOOP", "source_ref": ref_a},
                    {"id": "gtr-b", "disposition": "LOOP", "source_ref": ref_b},
                    {"id": "gtr-live", "disposition": "LIVE"},
                    {"id": "gtr-fill", "disposition": "UNRESOLVED"},
                ],
            }],
            "decisions": [
                {"id": "decision-gtr-fill",
                 "question": "Resolve the outro fill now, or defer it to a labeled preview?",
                 "options": ["play_live", "defer_unresolved"]},
            ],
            "patterns": [
                {"id": "pattern-a", "name": "Riff A", "track": "Guitar",
                 "span_ids": ["gtr-a"], "bars": 2, "disposition": "LOOP"},
                {"id": "pattern-b", "name": "Riff B", "track": "Guitar",
                 "span_ids": ["gtr-b"], "bars": 2, "disposition": "LOOP"},
                {"id": "pattern-live", "name": "Live Fills", "track": "Guitar",
                 "span_ids": ["gtr-live"], "bars": 2, "disposition": "LIVE"},
                {"id": "pattern-fill", "name": "Outro Fill", "track": "Guitar",
                 "span_ids": ["gtr-fill"], "bars": 1, "disposition": "UNRESOLVED"},
            ],
            "sections": [
                # pattern-a is reused (placed) across two non-adjacent sections,
                # exercising requirement 4's repeated source-backed LOOP placement.
                {"id": "sec-verse-1", "name": "Verse", "bars": 2,
                 "active_pattern_ids": ["pattern-a"]},
                {"id": "sec-verse-2", "name": "Verse", "bars": 2,
                 "active_pattern_ids": ["pattern-a"]},
                {"id": "sec-chorus", "name": "Chorus", "bars": 2,
                 "active_pattern_ids": ["pattern-b"]},
                {"id": "sec-bridge", "name": "Bridge", "bars": 2,
                 "active_pattern_ids": ["pattern-live"]},
                {"id": "sec-outro", "name": "Outro", "bars": 1,
                 "active_pattern_ids": ["pattern-fill"]},
            ],
        }

    def test_full_pipeline_multi_section_reuse_live_unresolved(self):
        rel_path, digest = self._write_fixture(bars=4)
        manifest = self._manifest(rel_path, digest)
        resolutions = [{"decision_id": "decision-gtr-fill", "option": "defer_unresolved"}]
        performance = {"status": "partial",
                       "limitations": ["outro fill deferred pending a player decision"],
                       "consent": "reviewed and accepted",
                       "performance": {"players": 1, "roles": ["Player 1 performs guitar"]}}

        manifest_bytes_before = json.dumps(manifest).encode("utf-8")
        self.manifest_path.write_bytes(manifest_bytes_before)
        self.resolutions_path.write_text(json.dumps(resolutions), encoding="utf-8")
        self.performance_path.write_text(json.dumps(performance), encoding="utf-8")

        # --- step 1: real compile_performance.py CLI -------------------------------
        code = compile_main(["--manifest", str(self.manifest_path),
                             "--resolutions", str(self.resolutions_path),
                             "--performance", str(self.performance_path),
                             "--output", str(self.output_path)])
        self.assertEqual(code, 0)

        # requirement 4: analysis bytes unchanged -- compiling never mutates the
        # original analysis manifest file on disk.
        self.assertEqual(self.manifest_path.read_bytes(), manifest_bytes_before)

        compiled = json.loads(self.output_path.read_text(encoding="utf-8"))
        self.assertEqual(compiled["fingerprints"]["analysis_sha256"],
                         canonical_sha256(json.loads(manifest_bytes_before)))

        instruments = compiled["instruments"]
        self.assertEqual(len(instruments), 1)
        instrument = instruments[0]
        roles = [(t["role"], t.get("pattern_id")) for t in instrument["output_tracks"]]
        self.assertEqual(roles, [("live", None), ("loop", "pattern-a"),
                                 ("loop", "pattern-b"), ("unresolved", None)])

        # Two placements reuse pattern-a's single output track across the two
        # non-adjacent Verse sections (bars 0-1 and 2-3).
        loop_a_track = instrument["output_tracks"][1]["id"]
        loop_a_placements = [p for p in compiled["placements"]
                             if p["output_track_id"] == loop_a_track]
        self.assertEqual(len(loop_a_placements), 2)
        self.assertEqual(sorted(p["output_bar_range"] for p in loop_a_placements),
                         [[0, 1], [2, 3]])
        self.assertTrue(all(p["material_id"] == "pattern-a" for p in loop_a_placements))
        self.assertTrue(all(p["source_ref"]["written_master_bars"] == [1, 2]
                            for p in loop_a_placements))

        # --- step 2: real write_arrangement.mjs writer, with the freshness
        # preflight flags exercised against the real, untouched analysis/resolutions
        # files written above. --------------------------------------------------
        result = subprocess.run(
            ["node", str(WRITER), "--performance", str(self.output_path),
             "--song-dir", str(self.song_dir), "--output", str(self.gp_output),
             "--analysis", str(self.manifest_path), "--resolutions", str(self.resolutions_path)],
            capture_output=True, text=True, timeout=90, check=False,
        )
        self.assertEqual(result.returncode, 0, result.stderr)

        # --- step 3: inspect the real .gp bar-by-bar/track-by-track ----------------
        actual = inspect(self.gp_output)
        self.assertEqual(actual["bar_count"], 9)  # 2+2+2+2+1
        self.assertEqual(actual["track_count"], 2)
        names = [t["name"] for t in actual["tracks"]]
        self.assertEqual(names, ["Guitar (loop)", "Guitar (loop)"])

        loop_a, loop_b = actual["tracks"]

        # loop-a: fret pattern [1, 2] repeated at bars 1-2 (Verse 1) and 3-4 (Verse 2)
        # -- no off-by-one in either occurrence's placement.
        self.assertEqual([(n["bar"], n["fret"]) for n in loop_a["notes"]],
                         [(1, 1), (2, 2), (3, 1), (4, 2)])

        # loop-b: fret pattern [3, 4] placed only at bars 5-6 (Chorus).
        self.assertEqual([(n["bar"], n["fret"]) for n in loop_b["notes"]],
                         [(5, 3), (6, 4)])

        with __import__("zipfile").ZipFile(self.gp_output) as zf:
            xml = zf.read("Content/score.gpif").decode("utf-8")
        self.assertNotIn("LIVE: bars 7-8", xml)
        self.assertNotIn("UNRESOLVED: bars 9-9", xml)


if __name__ == "__main__":
    unittest.main()
